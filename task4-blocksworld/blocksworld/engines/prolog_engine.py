"""Blocks World planning with SWI-Prolog symbolic search.

The planner itself lives in ``blocksworld/prolog/blocksworld.pl``. This module
only marshals data across the process boundary: it writes the instance out as
Prolog facts, runs the chosen strategy, and parses the JSON that comes back.

Execution paths, in order of preference -- native ``swipl`` on ``PATH``, then
the ``swipl-wasm`` runner under Node. The Prolog source is identical in both;
only the invocation differs, and ``stats['mode']`` records which was used so
benchmark output can never silently mix them.

If no Prolog toolchain exists this raises :class:`EngineUnavailable`. It never
hands the problem to Z3: an engine comparison in which one engine quietly
answers for the other would be worthless.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any

from ..model import Action, Instance, Plan, State
from .base import Engine, EngineUnavailable, PlanResult

_PROLOG_DIR = Path(__file__).resolve().parent.parent / "prolog"
_MODEL = _PROLOG_DIR / "blocksworld.pl"
_WASM_RUNNER = _PROLOG_DIR / "run_wasm.mjs"
_WASM_MODULE = _PROLOG_DIR / "node_modules" / "swipl-wasm"

#: Search strategies implemented in the Prolog model.
STRATEGIES = ("idastar", "iddfs", "bfs")
DEFAULT_STRATEGY = "idastar"


def _atom(name: str) -> str:
    """Quote a block name so Prolog reads it as an atom, not a variable."""
    escaped = name.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def _stacks_term(state: State) -> str:
    inner = ", ".join(
        "[" + ", ".join(_atom(b) for b in stack) + "]" for stack in state.stacks
    )
    return f"[{inner}]"


def instance_to_facts(instance: Instance) -> str:
    """Render an instance as the Prolog facts ``blocksworld.pl`` expects."""
    lines = [
        "% generated by blocksworld.engines.prolog_engine - do not edit",
        f"table_capacity({instance.table_capacity}).",
        f"initial_state({_stacks_term(instance.initial)}).",
        f"goal_state({_stacks_term(instance.goal)}).",
    ]
    lines += [f"block({_atom(b)})." for b in instance.blocks]
    return "\n".join(lines) + "\n"


class PrologEngine(Engine):
    """Symbolic search backend."""

    name = "prolog"

    def __init__(
        self, *, strategy: str = DEFAULT_STRATEGY, prefer: str | None = None
    ) -> None:
        if strategy not in STRATEGIES:
            raise ValueError(
                f"unknown strategy {strategy!r}; choose from {STRATEGIES}"
            )
        self.strategy = strategy
        self._prefer = prefer

    # -- toolchain discovery ------------------------------------------------

    def _native_binary(self) -> str | None:
        if self._prefer == "wasm":
            return None
        return shutil.which("swipl")

    def _wasm_ready(self) -> bool:
        if self._prefer == "native":
            return False
        return (
            shutil.which("node") is not None
            and _WASM_RUNNER.is_file()
            and _WASM_MODULE.is_dir()
        )

    def mode(self) -> str:
        if self._native_binary():
            return "native"
        if self._wasm_ready():
            return "wasm"
        return "unavailable"

    def available(self) -> bool:
        return self.mode() != "unavailable"

    def version(self) -> str:
        mode = self.mode()
        if mode == "native":
            binary = self._native_binary()
            assert binary is not None
            out = subprocess.run(
                [binary, "--version"], capture_output=True, text=True, timeout=30
            )
            return f"{out.stdout.strip()} (native)"
        if mode == "wasm":
            try:
                version = json.loads((_WASM_MODULE / "package.json").read_text())[
                    "version"
                ]
            except Exception:  # noqa: BLE001 - version string is cosmetic
                version = "unknown"
            return f"SWI-Prolog via swipl-wasm {version}"
        raise EngineUnavailable(
            "no Prolog toolchain found: install SWI-Prolog (`swipl` on PATH), "
            "or run `npm install` in blocksworld/prolog/ for the WASM fallback"
        )

    # -- invocation ---------------------------------------------------------

    def _run(
        self, instance: Instance, max_depth: int, timeout: float | None
    ) -> tuple[dict[str, Any], float, str]:
        path = self.mode()
        if path == "unavailable":
            raise EngineUnavailable(
                "no Prolog toolchain found: install SWI-Prolog (`swipl` on PATH), "
                "or run `npm install` in blocksworld/prolog/ for the WASM fallback"
            )

        with tempfile.TemporaryDirectory(prefix="bw-pl-") as tmp:
            facts = Path(tmp) / "facts.pl"
            facts.write_text(instance_to_facts(instance))

            if path == "native":
                binary = self._native_binary()
                assert binary is not None
                # `--` separates the consulted model from the data arguments;
                # see the longer note in tetravex/solvers/prolog_solver.py.
                # Omitting it, or moving it ahead of _MODEL, breaks the native
                # path in two different and equally silent ways.
                cmd = [
                    binary, "-q", "-g", "main", "-t", "halt",
                    str(_MODEL), "--", str(facts), self.strategy, str(max_depth),
                ]
            else:
                cmd = [
                    "node", str(_WASM_RUNNER),
                    str(facts), self.strategy, str(max_depth), str(_MODEL),
                ]

            start = time.perf_counter()
            try:
                proc = subprocess.run(
                    cmd, capture_output=True, text=True,
                    timeout=timeout, cwd=str(_PROLOG_DIR),
                )
            except subprocess.TimeoutExpired:
                return (
                    {"status": "unknown", "timeout": True, "stats": {}},
                    time.perf_counter() - start,
                    path,
                )
            elapsed = time.perf_counter() - start

        if proc.returncode != 0:
            raise RuntimeError(
                f"Prolog exited with code {proc.returncode}\n"
                f"stdout: {proc.stdout[-2000:]}\nstderr: {proc.stderr[-2000:]}"
            )

        line = next(
            (ln for ln in reversed(proc.stdout.splitlines())
             if ln.strip().startswith("{")),
            None,
        )
        if line is None:
            raise RuntimeError(
                f"no JSON on Prolog stdout.\nstdout: {proc.stdout[-2000:]}\n"
                f"stderr: {proc.stderr[-2000:]}"
            )
        return (json.loads(line), elapsed, path)

    # -- public API ---------------------------------------------------------

    def plan(
        self,
        instance: Instance,
        *,
        timeout: float | None = None,
        max_depth: int | None = None,
    ) -> PlanResult:
        structural = instance.structurally_unsolvable()
        if structural is not None:
            plan = Plan(
                instance.id, "unsat", (), self.name,
                {"reason": structural, "proof": "structural", "mode": self.mode()},
            )
            return PlanResult(plan, 0.0, self.name, plan.stats)

        bound = max_depth
        if bound is None:
            bound = instance.completeness_bound
        if bound is None:
            # No sound bound exists (restricted table). Use a generous ceiling
            # and report `limit` rather than `unsat` if it is reached.
            bound = 4 * instance.n_blocks

        raw, elapsed, path = self._run(instance, bound, timeout)
        stats = dict(raw.get("stats") or {})
        stats["mode"] = path
        stats["max_depth"] = bound
        status = raw.get("status", "unknown")

        if status == "sat":
            actions = tuple(
                Action(a["block"], a["from"], a["to"]) for a in raw.get("plan", [])
            )
            plan = Plan(instance.id, "sat", actions, self.name, stats)
            return PlanResult(plan, elapsed, self.name, stats)

        if status == "unsat":
            # Only BFS can reach this: it exhausted the reachable state space.
            stats["proof"] = "state-space-exhausted"
            plan = Plan(instance.id, "unsat", (), self.name, stats)
            return PlanResult(plan, elapsed, self.name, stats)

        if status == "limit":
            # The depth ceiling was reached. If that ceiling was itself a sound
            # completeness bound, nothing longer could have helped and the
            # instance is genuinely unsolvable.
            if (
                instance.completeness_bound is not None
                and bound >= instance.completeness_bound
            ):
                stats["proof"] = f"no plan within completeness bound {bound}"
                plan = Plan(instance.id, "unsat", (), self.name, stats)
            else:
                plan = Plan(instance.id, "limit", (), self.name, stats)
            return PlanResult(plan, elapsed, self.name, stats)

        plan = Plan(instance.id, "unknown", (), self.name, stats)
        return PlanResult(plan, elapsed, self.name, stats)
