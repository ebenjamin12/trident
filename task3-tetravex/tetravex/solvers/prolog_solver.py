"""TetraVex solved with SWI-Prolog and CLP(FD).

The constraint model lives in ``tetravex/prolog/tetravex.pl``. This module only
marshals data across the process boundary: it writes the instance out as
Prolog facts, invokes the model, and parses the single line of JSON that comes
back.

Two execution paths, in order of preference:

native
    A ``swipl`` binary on ``PATH``. Fastest, and the standard way to run the
    model. No extra dependencies.
wasm
    The ``swipl-wasm`` npm package driven through Node, used when SWI-Prolog
    is not installed. The Prolog source is byte-for-byte the same; only the
    invocation differs.

Which path was taken is reported in ``SolveResult.stats['mode']`` so that
benchmark output never silently mixes the two.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any

from ..model import Instance, Solution
from .base import Solver, SolveResult, SolverUnavailable

_PROLOG_DIR = Path(__file__).resolve().parent.parent / "prolog"
_MODEL = _PROLOG_DIR / "tetravex.pl"
_WASM_RUNNER = _PROLOG_DIR / "run_wasm.mjs"
_WASM_MODULE = _PROLOG_DIR / "node_modules" / "swipl-wasm"


def _bool_atom(value: bool) -> str:
    return "true" if value else "false"


def instance_to_facts(instance: Instance) -> str:
    """Render an instance as the Prolog facts ``tetravex.pl`` expects."""
    lines = [
        "% generated by tetravex.solvers.prolog_solver - do not edit",
        f"dims({instance.rows}, {instance.cols}).",
        f"symbols({instance.symbols}).",
        f"allow_rotation({_bool_atom(instance.allow_rotation)}).",
    ]
    if instance.border is None:
        lines.append("border_spec(none).")
    else:
        b = instance.border
        lines.append(
            f"border_spec(border({list(b.top)}, {list(b.right)}, {list(b.bottom)}, {list(b.left)}))."
        )
    for tile in instance.tiles:
        lines.append(
            f"tile({tile.id}, {tile.top}, {tile.right}, {tile.bottom}, {tile.left})."
        )
    return "\n".join(lines) + "\n"


class PrologSolver(Solver):
    """CLP(FD) backend."""

    name = "prolog"

    def __init__(self, *, prefer: str | None = None) -> None:
        """``prefer`` may be ``'native'`` or ``'wasm'`` to pin the execution
        path; by default native is used when available."""
        self._prefer = prefer

    # -- toolchain discovery ------------------------------------------------

    def _native_binary(self) -> str | None:
        if self._prefer == "wasm":
            return None
        return shutil.which("swipl")

    def _wasm_ready(self) -> bool:
        if self._prefer == "native":
            return False
        return (
            shutil.which("node") is not None
            and _WASM_RUNNER.is_file()
            and _WASM_MODULE.is_dir()
        )

    def mode(self) -> str:
        if self._native_binary():
            return "native"
        if self._wasm_ready():
            return "wasm"
        return "unavailable"

    def available(self) -> bool:
        return self.mode() != "unavailable"

    def version(self) -> str:
        mode = self.mode()
        if mode == "native":
            binary = self._native_binary()
            assert binary is not None
            out = subprocess.run(
                [binary, "--version"], capture_output=True, text=True, timeout=30
            )
            return f"{out.stdout.strip()} (native)"
        if mode == "wasm":
            pkg = _WASM_MODULE / "package.json"
            try:
                version = json.loads(pkg.read_text())["version"]
            except Exception:  # noqa: BLE001 - version is cosmetic
                version = "unknown"
            return f"SWI-Prolog via swipl-wasm {version}"
        raise SolverUnavailable(
            "no Prolog toolchain found: install SWI-Prolog (`swipl` on PATH), "
            "or run `npm install` in tetravex/prolog/ for the WASM fallback"
        )

    # -- invocation ---------------------------------------------------------

    def _run(
        self, instance: Instance, mode: str, timeout: float | None
    ) -> tuple[dict[str, Any], float, str]:
        path = self.mode()
        if path == "unavailable":
            raise SolverUnavailable(
                "no Prolog toolchain found: install SWI-Prolog (`swipl` on PATH), "
                "or run `npm install` in tetravex/prolog/ for the WASM fallback"
            )

        with tempfile.TemporaryDirectory(prefix="tetravex-pl-") as tmp:
            facts = Path(tmp) / "facts.pl"
            facts.write_text(instance_to_facts(instance))

            if path == "native":
                binary = self._native_binary()
                assert binary is not None
                # The `--` is load-bearing and its position matters twice over.
                # Without it, swipl treats the facts file as a second source
                # file to consult, so it never reaches `argv` and `main/0`
                # fails with no output (exit 1). Placed *before* _MODEL it is
                # worse: the model stops being consulted as a script, `main/0`
                # goes undefined, and swipl silently resolves `main` against
                # library(main)'s `main/1` instead (exit 2). So: model first,
                # then `--`, then the data arguments.
                cmd = [
                    binary,
                    "-q",
                    "-g", "main",
                    "-t", "halt",
                    str(_MODEL),
                    "--",
                    str(facts),
                    mode,
                ]
            else:
                cmd = [
                    "node",
                    str(_WASM_RUNNER),
                    str(facts),
                    mode,
                    str(_MODEL),
                ]

            start = time.perf_counter()
            try:
                proc = subprocess.run(
                    cmd,
                    capture_output=True,
                    text=True,
                    timeout=timeout,
                    cwd=str(_PROLOG_DIR),
                    env={**os.environ, "SWIPL_QUIET": "1"},
                )
            except subprocess.TimeoutExpired:
                elapsed = time.perf_counter() - start
                return ({"status": "unknown", "timeout": True}, elapsed, path)
            elapsed = time.perf_counter() - start

        if proc.returncode != 0:
            raise RuntimeError(
                f"Prolog exited with code {proc.returncode}\n"
                f"stdout: {proc.stdout[-2000:]}\nstderr: {proc.stderr[-2000:]}"
            )

        line = next(
            (ln for ln in reversed(proc.stdout.splitlines()) if ln.strip().startswith("{")),
            None,
        )
        if line is None:
            raise RuntimeError(
                f"no JSON on Prolog stdout.\nstdout: {proc.stdout[-2000:]}\n"
                f"stderr: {proc.stderr[-2000:]}"
            )
        return (json.loads(line), elapsed, path)

    # -- parsing ------------------------------------------------------------

    @staticmethod
    def _grid_to_solution(
        instance: Instance, grid: list, stats: dict[str, Any]
    ) -> Solution:
        assignment = [
            (cell["tile"], cell["rot"]) for row in grid for cell in row
        ]
        return Solution.from_assignment(
            instance, assignment, engine="prolog", stats=stats
        )

    # -- public API ---------------------------------------------------------

    def solve(self, instance: Instance, *, timeout: float | None = None) -> SolveResult:
        raw, elapsed, path = self._run(instance, "one", timeout)
        stats = dict(raw.get("stats") or {})
        stats["mode"] = path
        status = raw.get("status", "unknown")
        if status == "sat":
            solution = self._grid_to_solution(instance, raw["grid"], stats)
            return SolveResult("sat", solution, None, None, elapsed, self.name, stats)
        if status == "unsat":
            return SolveResult("unsat", None, None, None, elapsed, self.name, stats)
        return SolveResult("unknown", None, None, None, elapsed, self.name, stats)

    def solve_unique(
        self, instance: Instance, *, timeout: float | None = None
    ) -> SolveResult:
        raw, elapsed, path = self._run(instance, "unique", timeout)
        stats = dict(raw.get("stats") or {})
        stats["mode"] = path
        status = raw.get("status", "unknown")
        if status == "unsat":
            return SolveResult("unsat", None, None, None, elapsed, self.name, stats)
        if status != "sat":
            return SolveResult("unknown", None, None, None, elapsed, self.name, stats)

        solution = self._grid_to_solution(instance, raw["grid"], stats)
        unique_raw = raw.get("unique")
        unique = None if unique_raw in (None, "null") else bool(unique_raw)
        second = None
        if raw.get("second"):
            second = self._grid_to_solution(instance, raw["second"], {})
        return SolveResult("sat", solution, unique, second, elapsed, self.name, stats)
